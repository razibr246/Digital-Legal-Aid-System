/**
 * Fast in-memory search across universal inquiries.
 * Returns best matched items sorted by relevance.
 */
export function searchUniversalInquiries(query: string, maxResults = 2): InquiryItem[] {
  if (!query || query.trim().length === 0) return [];
  const normalizedQuery = query.toLowerCase().trim();

  const scored = UNIVERSAL_INQUIRIES.map((item) => {
    let score = 0;

    // Check exact case id matches (e.g. DLAS-2025-0992)
    if (normalizedQuery.includes("dlas-2025-0992") && item.id === "case_status_lawyer_audit") {
      score += 100;
    }

    // Check keyword matches
    for (const kw of item.keywords) {
      if (normalizedQuery.includes(kw.toLowerCase())) {
        score += 10;
      }
    }

    // Check question content matches
    const questionWords = item.questionBn.split(/\s+/);
    for (const w of questionWords) {
      if (w.length > 2 && normalizedQuery.includes(w)) {
        score += 3;
      }
    }

    // Prioritize critical urgent safety protocols
    if (score > 0 && item.isUrgent) {
      score += 5;
    }

    return { item, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxResults)
    .map((s) => s.item);
}

