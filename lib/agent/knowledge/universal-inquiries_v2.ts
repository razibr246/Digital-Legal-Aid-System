/**
 * Fast in-memory search across universal inquiries.
 * Returns best matched items sorted by relevance.
 */
export function searchUniversalInquiries(query: string, maxResults = 2): InquiryItem[] {
  if (!query || query.trim().length === 0) return [];
  const normalize = (value: string) => value.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, " ").trim();
  const normalizedQuery = normalize(query);
  const queryTokens = new Set(normalizedQuery.split(/\s+/).filter(Boolean));
  const stopWords = new Set([
    "আমি", "আপনার", "আমাদের", "কোন", "কোনো", "কি", "কোনটি", "আইন", "অধীনে", "করা", "হয়", "হবে", "আছে", "এই", "এর", "ও", "প্রশ্ন", "সমস্যা",
  ]);
  const urgentSignal = /জরুরি|নির্যাতন|হুমকি|ছবি|ব্ল্যাকমেইল|অপরাধ|সাইবার|দমন|জিডি|ইজারত|আশ্রয়|ঝুঁকি|আইনজীবী পাব|emergency|violence|threat|abuse|blackmail/;

  const scored = UNIVERSAL_INQUIRIES.map((item) => {
    let score = 0;

    if (normalizedQuery.includes("dlas-2025-0992") && item.id === "case_status_lawyer_audit") {
      score += 100;
    }

    for (const keyword of item.keywords) {
      const normalizedKeyword = normalize(keyword);
      if (normalizedKeyword && normalizedQuery.includes(normalizedKeyword)) {
        score += 20;
      }
    }

    for (const word of item.questionBn.split(/\s+/)) {
      const normalizedWord = normalize(word);
      if (
        normalizedWord.length > 3 &&
        !stopWords.has(normalizedWord) &&
        queryTokens.has(normalizedWord)
      ) {
        score += 4;
      }
    }

    if (score > 0 && item.isUrgent && urgentSignal.test(normalizedQuery)) {
      score += 5;
    }

    return { item, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxResults)
    .map((s) => s.item);
}

