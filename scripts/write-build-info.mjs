/**
 * Writes the build identity that components/build-stamp.tsx renders.
 *
 * The shell used to show a hardcoded "সর্বশেষ হালনাগাদ: ৭ সেপ্টেম্বর ২০২৬", so there
 * was no way to tell a fresh deploy from a cached one by looking at the page. Reading
 * the id out of the `/_next/static/…` path does not work on the App Router — those
 * chunks are `chunks/…` with no build segment — so it has to be recorded at build time.
 *
 *   node scripts/write-build-info.mjs
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const git = (...args) => {
  try {
    return execFileSync("git", args, { encoding: "utf8" }).trim();
  } catch {
    return "";
  }
};

const sha = git("rev-parse", "--short", "HEAD") || "local";
const at = new Date().toISOString();

const body = `// GENERATED by scripts/write-build-info.mjs — do not edit.
// Lets the running page state which build it is, so a stale deploy is visible
// instead of being argued about.
export const BUILD_SHA = ${JSON.stringify(sha)};
export const BUILD_AT = ${JSON.stringify(at)};
`;

writeFileSync(resolve("lib/build-info.ts"), body, "utf8");
console.log(`build-info: ${sha} @ ${at}`);
